@pytest.mark.parametrize(
    ("lead", "trail", "expected"),
    [
        (False, False, '"exact words here"'),
        (True, False, '…"exact words here"'),
        (False, True, '"exact words here"…'),
        (True, True, '…"exact words here"…'),
    ],
)
def test_ellipses_are_outside_the_quotation_marks(lead: bool, trail: bool, expected: str) -> None:
    q = quote(1, "exact words here", lead=lead, trail=trail)
    assert quote_display(q) == expected
    # The quotation marks enclose exactly the verbatim text, nothing added inside them.
    assert f'"{q.text}"' in quote_display(q)
    inner = quote_display(q).split('"')[1]
    assert inner == q.text


def test_truncated_quote_ending_in_punctuation_keeps_ellipsis_outside() -> None:
    text = "SYNTHETIC FIXTURE the withdrawal was delayed for days."
    truncated = quote(1, text, trail=True)
    whole = quote(2, text)
    assert quote_display(truncated) == f'"{text}"…'
    assert quote_display(whole) == f'"{text}"'
    for q in (truncated, whole):
        assert not quote_display(q).endswith('…"')  # never "text.…"


