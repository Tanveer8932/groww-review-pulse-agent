def _rendered_with_words(n: int) -> RenderedPulse:
    marker_words = count_words(audit_marker("2026-W42", "0" * 64))
    body = " ".join(["word"] * (n - marker_words)) + "\n"
    return RenderedPulse("2026-W42", body, body, 0)


def test_word_limit_boundary_250_passes_251_fails() -> None:
    at_limit, over = _rendered_with_words(MAX_WORDS), _rendered_with_words(MAX_WORDS + 1)
    assert count_words(at_limit.full_text) == 250
    assert check_word_limit(at_limit).passed
    result = check_word_limit(over)
    assert not result.passed
    assert "251 words" in result.detail


def _long_content(name_words: int, action_words: int) -> dict[str, object]:
    """Maximum-length quotes (35 words each) with adjustable theme and action lengths."""
    quotes = tuple(
        "SYNTHETIC FIXTURE " + " ".join(f"w{q}x{i}" for i in range(33)) for q in range(3)
    )
    name = " ".join(["Slow"] * name_words)
    return {
        "names": (f"{name} orders", f"{name} logins", f"{name} withdrawals"),
        "quote_texts": quotes,
        "actions": tuple(
            "Fix " + " ".join(["delays"] * (action_words - 2)) + f" area{i}" for i in range(3)
        ),
    }


@pytest.mark.parametrize(
    ("name_words", "action_words", "level", "words"),
    [(1, 18, 0, 237), (4, 20, 1, 249), (4, 22, 2, 246)],
)
def test_shrink_path_drops_metadata_until_the_pulse_fits(
    name_words: int, action_words: int, level: int, words: int
) -> None:
    content = pulse_content(synthetic=False, **_long_content(name_words, action_words))  # type: ignore[arg-type]
    assert all(count_words(q.text) == 35 for q in content.quotes)
    rendered = render_within_limit(content)
    assert (rendered.detail_level, count_words(rendered.full_text)) == (level, words)
    assert check_word_limit(rendered).passed
    if level:
        assert count_words(render(content, level - 1).full_text) > MAX_WORDS
    for q in content.quotes:  # quotes are never shortened
        assert quote_display(q) in rendered.body_text


