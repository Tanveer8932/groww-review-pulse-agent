@pytest.mark.parametrize(
    ("field", "value", "where"),
    [
        ("action", "Call the user back on 9876543210", "action 1"),
        ("action", "Email rahul@example.com about refunds", "action 1"),
        ("name", "Issues for Mr. Sharma", "theme 1 name"),
        ("quote", "SYNTHETIC FIXTURE call me on 9876543210 about my stuck refund", "quote 1"),
    ],
)
def test_pii_anywhere_in_the_report_fails_safely(field: str, value: str, where: str) -> None:
    base = pulse_content(synthetic=False)
    if field == "action":
        content = dataclasses.replace(
            base,
            actions=(
                ActionIdea(theme_id="T1", action=value, owner_area="Product"),
                *base.actions[1:],
            ),
        )
    elif field == "name":
        content = dataclasses.replace(
            base, themes=(base.themes[0].model_copy(update={"name": value}), *base.themes[1:])
        )
    else:
        content = dataclasses.replace(base, quotes=(quote(1, value), *base.quotes[1:]))
    rendered = render(content)
    result = check_pii(content, rendered)
    assert not result.passed
    assert where in result.detail
    assert "full plain text" in result.detail
    # Nothing was redacted to make the scan pass: the value is still in the rendering.
    assert value in rendered.body_text
    # The message names types and places, never the detected value.
    assert "9876543210" not in result.detail
    assert "rahul@" not in result.detail


