"""Deterministic pulse rendering (architecture §6.5; Phase 4).

The pulse is filled from a fixed template. Every value comes from verified, code-computed
data (:class:`PulseContent`); nothing is generated here, and no LLM is involved.

Quotes are inserted **exactly** as stored: never escaped, trimmed, re-cased, or shortened.
The quotation marks enclose only the verbatim text. When a quote is a span inside a longer
review, an ellipsis (``…``) is placed *outside* the quotation marks: ``…"verbatim span"…``.

Two renderings share one template: plain text (``body_text``, hashed and word-counted)
and Markdown (``body_markdown``, the same words with Markdown emphasis and list markers).
The audit marker line ``[groww-pulse:{iso_week}:{content_hash[:8]}]`` is placed above the
body in the saved files. It is not part of the hashed body, because the hash is in it.

**Detail levels.** Rendering starts at level 0 and, only if the word limit is exceeded,
drops optional metadata (never quotes, themes, actions, or counts):

* level 0: everything;
* level 1: action lines without the owner area;
* level 2: level 1, and theme lines without the average rating.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from datetime import date

from groww_pulse.models import ActionIdea, Quote, Theme

ELLIPSIS = "…"
TITLE = "Groww Review Pulse"
FOOTER = "Source: public Google Play reviews; anonymized. Generated by Groww Review Pulse Agent."
FALLBACK_NOTE = "Themes: fallback clustering."
SYNTHETIC_BANNER = "SYNTHETIC TEST DATA — NOT FOR PUBLICATION"
MAX_DETAIL_LEVEL = 2


@dataclass(frozen=True)
class PulseContent:
    """Verified inputs for one pulse. Built and checked by :mod:`groww_pulse.report.pipeline`."""

    iso_week: str
    window_start: date
    window_end: date
    n_collected: int
    n_analyzed: int
    themes: tuple[Theme, ...]  # the top 3, in rank order
    quotes: tuple[Quote, ...]
    actions: tuple[ActionIdea, ...]  # ordered by theme rank
    fallback_clustering: bool = False
    synthetic: bool = False


@dataclass(frozen=True)
class RenderedPulse:
    iso_week: str
    body_text: str
    body_markdown: str
    detail_level: int

    @property
    def content_hash(self) -> str:
        return hashlib.sha256(self.body_text.encode("utf-8")).hexdigest()

    @property
    def marker(self) -> str:
        """Audit marker line (architecture §6.6), placed above the body in saved files."""
        return audit_marker(self.iso_week, self.content_hash)

    @property
    def full_text(self) -> str:
        return f"{self.marker}\n{self.body_text}"

    @property
    def full_markdown(self) -> str:
        return f"{self.marker}\n\n{self.body_markdown}"


def audit_marker(iso_week: str, content_hash: str) -> str:
    return f"[groww-pulse:{iso_week}:{content_hash[:8]}]"


def iso_week_label(day: date) -> str:
    year, week, _ = day.isocalendar()
    return f"{year}-W{week:02d}"


def pct(share: float) -> str:
    """Percentage with one decimal, exactly as Phase 3 shows it to the LLM."""
    return f"{share * 100:.1f}"


def quote_display(quote: Quote) -> str:
    """The quote as printed: verbatim text in quotation marks, with ellipses outside them."""
    lead = ELLIPSIS if quote.leading_ellipsis else ""
    trail = ELLIPSIS if quote.trailing_ellipsis else ""
    return f'{lead}"{quote.text}"{trail}'


def _theme_line(rank: int, theme: Theme, detail_level: int) -> str:
    line = f"{rank}. {theme.name} — {theme.count} reviews ({pct(theme.share)}%)"
    if detail_level < 2 and theme.avg_rating is not None:
        line += f", avg {theme.avg_rating:.1f}★"
    return line


def _quote_line(quote: Quote) -> str:
    return f"{quote_display(quote)} ({quote.rating}★, {quote.created_at.date().isoformat()})"


def _action_line(rank: int, action: ActionIdea, detail_level: int) -> str:
    line = f"{rank}. {action.action}"
    if detail_level < 1 and action.owner_area:
        line += f" ({action.owner_area})"
    return line


def _footer(content: PulseContent) -> str:
    return f"{FOOTER} {FALLBACK_NOTE}" if content.fallback_clustering else FOOTER


def render(content: PulseContent, detail_level: int = 0) -> RenderedPulse:
    """Render ``content`` at ``detail_level`` (0 = full; see the module docstring)."""
    if not 0 <= detail_level <= MAX_DETAIL_LEVEL:
        raise ValueError(f"detail_level must be 0-{MAX_DETAIL_LEVEL}")
    title = f"{TITLE} — {content.iso_week}"
    window = (
        f"Window: {content.window_start.isoformat()} to {content.window_end.isoformat()} · "
        f"{content.n_analyzed} reviews analyzed (of {content.n_collected} collected)"
    )
    themes = [_theme_line(i, t, detail_level) for i, t in enumerate(content.themes, 1)]
    quotes = [_quote_line(q) for q in content.quotes]
    actions = [_action_line(i, a, detail_level) for i, a in enumerate(content.actions, 1)]
    banner = [SYNTHETIC_BANNER] if content.synthetic else []

    text_lines = [
        *banner,
        title,
        window,
        "",
        "Top themes",
        *themes,
        "",
        "What users say",
        *(f"• {q}" for q in quotes),
        "",
        "Action ideas",
        *actions,
        "",
        _footer(content),
    ]
    md_lines = [
        *(f"**{b}**\n" for b in banner),
        f"## {title}",
        "",
        window.replace("Window:", "**Window:**", 1),
        "",
        "**Top themes**",
        "",
        *themes,
        "",
        "**What users say**",
        "",
        *(f"- {q}" for q in quotes),
        "",
        "**Action ideas**",
        "",
        *actions,
        "",
        f"*{_footer(content)}*",
    ]
    return RenderedPulse(
        iso_week=content.iso_week,
        body_text="\n".join(text_lines) + "\n",
        body_markdown="\n".join(md_lines) + "\n",
        detail_level=detail_level,
    )
